"""Copy the CAD-section SVG paths used by the prototype page (motor cross-section and
gearbox profiles) into src/content/svgPaths.ts, unchanged.

Usage: python -I scripts/extract_svg_paths.py reference/prototype/Main.dc.html src/content/svgPaths.ts
"""
import re
import sys

# (export name, 1-based line in Main.dc.html)
PATHS = [
    ("ROTOR_RING", 329),
    ("STATOR", 330),
    ("COIL", 332),
    ("GEAR_RING", 466),
    ("CARRIER", 469),
    ("PLANET_0", 474),
    ("PLANET_1", 484),
    ("PLANET_2", 493),
    ("SUN", 502),
]


def main(src, out):
    lines = open(src, encoding="utf-8").read().split("\n")
    parts = ["/* CAD mid-plane section profiles (mm, SVG coords: x right, y down = top view).",
             "   Generated by scripts/extract_svg_paths.py from reference/prototype/Main.dc.html — do not edit. */", ""]
    for name, ln in PATHS:
        m = re.search(r'<path d="([^"]+)"', lines[ln - 1])
        if not m:
            raise SystemExit(f"no path on line {ln} for {name}")
        parts.append(f"export const {name} = {m.group(1)!r};".replace("'", '"'))
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(parts) + "\n")
    print("wrote", len(PATHS), "paths to", out)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
